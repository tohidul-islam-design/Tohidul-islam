import { chromium } from 'playwright';
import { mkdirSync } from 'fs';
const site = 'https://bunon-beryl.vercel.app';
const out = 'assets/image/works/bunon-raw';
mkdirSync(out, { recursive: true });
const prep = "try{localStorage.setItem('bunon-cookies','all');sessionStorage.setItem('bunon-promo-seen','1')}catch(e){}";
const browser = await chromium.launch({ args: ['--use-gl=swiftshader', '--enable-unsafe-swiftshader'] });
const wait = ms => new Promise(r => setTimeout(r, ms));
async function settle(page) { await page.waitForLoadState('networkidle').catch(() => {}); await wait(3500); await page.keyboard.press('Escape'); await wait(400); }
const desk = await browser.newContext({ viewport: { width: 1440, height: 900 }, deviceScaleFactor: 1 });
await desk.addInitScript(prep);
const p = await desk.newPage();
await p.goto(site + '/'); await settle(p); await p.screenshot({ path: `${out}/home.png` });
await p.screenshot({ path: `${out}/home-full.png`, fullPage: true });
await p.goto(site + '/shop'); await settle(p);
await p.mouse.wheel(0, 420); await wait(1500); await p.screenshot({ path: `${out}/shop.png` });
await p.locator('a[href*="/product/"]').first().click(); await settle(p);
await p.screenshot({ path: `${out}/product.png` });
const sizes = p.locator('button:has-text("M"), button:has-text("38"), button:has-text("Free")');
if (await sizes.count()) await sizes.first().click().catch(() => {});
await p.getByRole('button', { name: /Add to cart/i }).first().click().catch(() => {});
await wait(1200); await p.screenshot({ path: `${out}/cart-drawer.png` });
await p.goto(site + '/checkout'); await settle(p); await p.screenshot({ path: `${out}/checkout.png` });
await p.goto(site + '/'); await settle(p);
await p.getByText('বাংলা').first().click().catch(() => {}); await wait(2000);
await p.screenshot({ path: `${out}/home-bangla.png` });
const mob = await browser.newContext({ viewport: { width: 390, height: 844 }, deviceScaleFactor: 2, isMobile: true, hasTouch: true });
await mob.addInitScript(prep);
const m = await mob.newPage();
await m.goto(site + '/'); await settle(m); await m.screenshot({ path: `${out}/home-mobile.png` });
await m.goto(site + '/shop'); await settle(m); await m.mouse.wheel(0, 500); await wait(1500); await m.screenshot({ path: `${out}/shop-mobile.png` });
await browser.close();
console.log('done');
